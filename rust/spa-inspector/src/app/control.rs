pub(super) struct Control {
    pub enabled: bool,
    #[cfg(not(target_arch = "wasm32"))]
    pub sender: mpsc::Sender<Envelope>,
    receiver: mpsc::Receiver<Envelope>,
    pub input: Vec<egui::Event>,
    pub deferred_input: std::collections::VecDeque<Vec<egui::Event>>,
    nodes: HashMap<u64, Node>,
    tree: Value,
    screenshot: Option<mpsc::Sender<Reply>>,
    #[cfg(not(target_arch = "wasm32"))]
    server: Option<spa_control::transport::Server>,
}
impl Control {
    pub fn new(ctx: &egui::Context) -> Self {
        let (sender, receiver) = mpsc::channel();
        #[cfg(target_arch = "wasm32")]
        {
            ctx.enable_accesskit();
            crate::browser_control::install(sender.clone(), ctx.clone());
        }
        #[cfg(not(target_arch = "wasm32"))]
        let _ = ctx;
        Self {
            enabled: cfg!(target_arch = "wasm32"),
            #[cfg(not(target_arch = "wasm32"))]
            sender,
            receiver,
            input: Vec::new(),
            deferred_input: Default::default(),
            nodes: HashMap::new(),
            tree: json!({"nodes":[]}),
            screenshot: None,
            #[cfg(not(target_arch = "wasm32"))]
            server: None,
        }
    }
}
impl InspectorApp {
    #[cfg(not(target_arch = "wasm32"))]
    pub fn enable_control(&mut self, port: u16, ctx: &egui::Context) -> std::io::Result<u16> {
        let wake = ctx.clone();
        let broker = spa_control::transport::Broker::native(
            self.control.sender.clone(),
            Arc::new(move || wake.request_repaint()),
        );
        let server = spa_control::transport::Server::start(port, broker)?;
        let port = server.port;
        self.control.server = Some(server);
        self.control.enabled = true;
        ctx.enable_accesskit();
        Ok(port)
    }
    pub(super) fn process_control(&mut self, ctx: &egui::Context) {
        let messages = self.control.receiver.try_iter().collect::<Vec<_>>();
        for envelope in messages {
            if envelope.command.method == "ui.screenshot" {
                if self.control.screenshot.is_some() {
                    let _ = envelope
                        .reply
                        .send(Err("A screenshot is already pending".into()));
                } else {
                    self.control.screenshot = Some(envelope.reply);
                    ctx.send_viewport_cmd(egui::ViewportCommand::Screenshot(egui::UserData::new(
                        "spa-control-screenshot",
                    )));
                    ctx.request_repaint();
                }
                continue;
            }
            let result = self.command(envelope.command, ctx);
            let _ = envelope.reply.send(result);
            ctx.request_repaint();
        }
    }
    pub(super) fn control_raw_input(&mut self, input: &egui::RawInput) {
        for event in &input.events {
            if let egui::Event::Screenshot {
                user_data, image, ..
            } = event
                && user_data
                    .data
                    .as_ref()
                    .and_then(|d| d.downcast_ref::<&str>())
                    == Some(&"spa-control-screenshot")
                && let Some(reply) = self.control.screenshot.take()
            {
                use image::ImageEncoder;
                let pixels = image
                    .pixels
                    .iter()
                    .flat_map(|p| p.to_array())
                    .collect::<Vec<_>>();
                let mut png = Vec::new();
                let result=image::codecs::png::PngEncoder::new(&mut png).write_image(&pixels,image.width() as u32,image.height() as u32,image::ExtendedColorType::Rgba8).map(|_|json!({"mimeType":"image/png","width":image.width(),"height":image.height(),"dataBase64":STANDARD.encode(png)})).map_err(|e|e.to_string());
                let _ = reply.send(result);
            }
        }
    }
    pub(super) fn capture_control_ui(&mut self, ctx: &egui::Context) {
        if !self.control.enabled {
            return;
        }
        let mut queue = vec![egui::accesskit_root_id()];
        let mut seen = HashSet::new();
        let mut nodes = HashMap::new();
        while let Some(id) = queue.pop() {
            if !seen.insert(id.value()) {
                continue;
            }
            if let Some(node) = ctx.accesskit_node_builder(id, |n| n.clone()) {
                for child in node.children() {
                    if child.0 != 0 {
                        // These nonzero IDs were generated by this egui context's
                        // own tree. Converting their hashed bits back preserves identity.
                        queue.push(unsafe { egui::Id::from_high_entropy_bits(child.0) });
                    }
                }
                nodes.insert(id.value(), node);
            }
        }
        let mut elements = Vec::new();
        for (id, node) in &nodes {
            let label = node.label().map(str::to_owned).unwrap_or_else(|| {
                node.labelled_by()
                    .iter()
                    .filter_map(|id| nodes.get(&id.0))
                    .filter_map(|n| n.value().or(n.label()))
                    .collect::<Vec<_>>()
                    .join(" ")
            });
            let mut actions = (0..64)
                .filter_map(Action::n)
                .filter(|a| node.supports_action(*a))
                .map(|a| format!("{a:?}"))
                .collect::<Vec<_>>();
            if can_set_text(node) && !node.supports_action(Action::SetValue) {
                actions.push("SetValue".into());
            }
            elements.push(json!({"id":id.to_string(),"role":format!("{:?}",node.role()),"label":label,"value":node.value(),"numericValue":node.numeric_value(),"disabled":node.is_disabled(),"hidden":node.is_hidden(),"selected":node.is_selected(),"toggled":node.toggled().map(|v|format!("{v:?}")),"bounds":node.bounds().map(|r|[r.x0,r.y0,r.x1,r.y1]),"children":node.children().iter().map(|id|id.0.to_string()).collect::<Vec<_>>(),"actions":actions}));
        }
        elements.sort_by(|a, b| a["id"].as_str().cmp(&b["id"].as_str()));
        self.control.nodes = nodes;
        self.control.tree = json!({"frame":ctx.cumulative_frame_nr(),"root":egui::accesskit_root_id().value().to_string(),"pixelsPerPoint":ctx.pixels_per_point(),"nodes":elements});
        #[cfg(target_arch = "wasm32")]
        crate::browser_control::flush();
    }
    pub(super) fn command(&mut self, command: Command, ctx: &egui::Context) -> Reply {
        let p = &command.params;
        match command.method.as_str() {
            "capabilities" => Ok(
                json!({"commands":spa_control::catalog(),"uiCoordinateUnits":"egui points","uiNodeIds":"decimal strings","filesReadByClient":true,"exportsWrittenByClient":true}),
            ),
            "state" => Ok(self.control_state(ctx)),
            "ui.elements" => Ok(self.control.tree.clone()),
            "ui.perform" => self.ui_command(p, ctx),
            "files.open" => {
                if self.busy() {
                    return Err("Wait for the current import or encoding change".into());
                }
                let files = p["files"].as_array().ok_or(
                    "App import requires files with name and dataBase64; CLI/MCP reads paths",
                )?;
                if files.is_empty() {
                    return Err("Choose at least one file".into());
                }
                if files.len() > platform::remaining_file_slots(self.files.len()) {
                    return Err("Choose files within the 32 open-file limit".into());
                }
                let mut inputs = Vec::new();
                let mut total = 0;
                for file in files {
                    let name = file["name"].as_str().ok_or("Missing file name")?;
                    let encoded = file["dataBase64"]
                        .as_str()
                        .ok_or("Missing base64 file data")?;
                    if encoded.len() > MAX_FILE_BYTES.div_ceil(3) * 4 {
                        return Err("File exceeds 64 MiB".into());
                    }
                    let bytes = STANDARD
                        .decode(encoded)
                        .map_err(|_| "Invalid base64 file data")?;
                    total += bytes.len();
                    if total > MAX_TOTAL_BYTES {
                        return Err("Selection exceeds 128 MiB".into());
                    }
                    inputs.push(platform::InputFile {
                        name: name.into(),
                        data: Ok(bytes),
                    });
                }
                self.picking = true;
                self.sender
                    .send(Event::Imported(inputs))
                    .map_err(|_| "Import queue disconnected")?;
                Ok(json!({"accepted":true,"queuedForFrame":ctx.cumulative_frame_nr()+1}))
            }
            "files.select" => {
                let index = index(p, "file")?;
                let file = self.files.get_mut(index).ok_or("Unknown file index")?;
                if let Some(series) = p.get("series") {
                    let series = series
                        .as_u64()
                        .and_then(|v| usize::try_from(v).ok())
                        .ok_or("Invalid series index")?;
                    if series
                        >= file
                            .document
                            .as_ref()
                            .ok_or("File has no decoded document")?
                            .series
                            .len()
                    {
                        return Err("Unknown series index".into());
                    }
                    file.selected_series = series;
                }
                prepare_series(file);
                self.selected_file = index;
                Ok(json!({"selectedFile":index,"selectedSeries":file.selected_series}))
            }
            "files.close" => {
                if self.busy() {
                    return Err("Wait for pending file reads".into());
                }
                let index = index(p, "file")?;
                if index >= self.files.len() {
                    return Err("Unknown file index".into());
                }
                self.files.remove(index);
                if index < self.selected_file {
                    self.selected_file -= 1;
                }
                self.selected_file = self.selected_file.min(self.files.len().saturating_sub(1));
                Ok(json!({"closed":index}))
            }
            "files.clear" => {
                if self.busy() {
                    return Err("Wait for pending file reads".into());
                }
                self.files.clear();
                self.selected_file = 0;
                Ok(json!({"closedAll":true}))
            }
            "view.set" => {
                let overlay = match p["mode"].as_str() {
                    Some("overlay") => true,
                    Some("individual") => false,
                    _ => return Err("Mode must be individual or overlay".into()),
                };
                let included = p
                    .get("includedFiles")
                    .map(|v| {
                        v.as_array()
                            .ok_or("includedFiles must be an array")
                            .and_then(|values| {
                                values
                                    .iter()
                                    .map(|v| {
                                        v.as_u64()
                                            .and_then(|i| usize::try_from(i).ok())
                                            .filter(|i| *i < self.files.len())
                                            .ok_or("Invalid included file index")
                                    })
                                    .collect::<Result<HashSet<_>, _>>()
                            })
                    })
                    .transpose()?;
                let units = if p.get("xUnitCode").is_some() || p.get("yUnitCode").is_some() {
                    let units = (u32_number(p, "xUnitCode")?, u32_number(p, "yUnitCode")?);
                    if !self
                        .files
                        .iter()
                        .filter_map(|f| f.document.as_ref())
                        .flat_map(|d| &d.series)
                        .any(|s| {
                            s.kind == "spectrum"
                                && (s.metadata.x_unit_code, s.metadata.y_unit_code) == units
                        })
                    {
                        return Err("No spectrum has those units".into());
                    }
                    Some(units)
                } else {
                    None
                };
                let reverse = p
                    .get("reverseX")
                    .map(|v| v.as_bool().ok_or("reverseX must be boolean"))
                    .transpose()?;
                if !overlay && reverse.is_some() {
                    self.current_file()?;
                }
                self.overlay = overlay;
                if let Some(included) = included {
                    for (i, file) in self.files.iter_mut().enumerate() {
                        file.overlay_enabled = included.contains(&i);
                    }
                }
                if let Some(units) = units {
                    self.overlay_units = Some(units);
                    self.overlay_plot.invalidate();
                    self.overlay_reverse = None;
                }
                if let Some(reverse) = reverse {
                    if overlay {
                        self.overlay_reverse = Some(reverse);
                    } else {
                        self.current_file_mut()?.reverse_x = reverse;
                    }
                }
                Ok(json!({"mode":if overlay{"overlay"}else{"individual"}}))
            }
            "plot.set_range" => {
                self.current_plot_mut()?
                    .interval(number(p, "min")?, number(p, "max")?)?;
                Ok(json!({"range":self.current_plot_mut()?.range}))
            }
            "plot.zoom" => {
                let center = p.get("center").map(|_| number(p, "center")).transpose()?;
                self.current_plot_mut()?
                    .zoom_by(number(p, "factor")?, center)?;
                Ok(json!({"range":self.current_plot_mut()?.range}))
            }
            "plot.reset" => {
                self.current_plot_mut()?.reset();
                Ok(json!({"range":self.current_plot_mut()?.range}))
            }
            "plot.preset" => {
                let x_code = if self.overlay {
                    self.overlay_units.map(|u| u.0)
                } else {
                    self.current_file()?
                        .document
                        .as_ref()
                        .and_then(|d| d.series.get(self.current_file().ok()?.selected_series))
                        .map(|s| s.metadata.x_unit_code)
                };
                if !x_code.is_some_and(|x| matches!(x, 1 | 32)) {
                    return Err("Sections require a wavenumber axis".into());
                }
                let plot = self.current_plot_mut()?;
                if p["clearPreview"] == true {
                    plot.automation_preview = None;
                    return Ok(json!({"previewCleared":true}));
                }
                let range = match p["section"].as_str() {
                    Some("4000-2500") => [2500.0, 4000.0],
                    Some("2500-1500") => [1500.0, 2500.0],
                    Some("1500-700") => [700.0, 1500.0],
                    _ => return Err("Unknown wavenumber section".into()),
                };
                if range[1] < plot.domain[0] || range[0] > plot.domain[1] {
                    return Err("Section is outside the data range".into());
                }
                if p["preview"] == true {
                    plot.automation_preview =
                        Some([range[0].max(plot.domain[0]), range[1].min(plot.domain[1])]);
                } else {
                    plot.interval(range[0], range[1])?;
                }
                Ok(json!({"range":plot.range,"previewRange":plot.automation_preview}))
            }
            "plot.trace" => {
                self.current_plot_mut()?.trace_visibility(
                    index(p, "trace")?,
                    p["visible"].as_bool().ok_or("visible must be boolean")?,
                )?;
                Ok(json!({"updated":true}))
            }
            "plot.sample" => self
                .current_plot_mut()?
                .sample(index(p, "trace")?, number(p, "x")?),
            "inspect" => self.inspect_command(p),
            "export" => {
                if p.get("preview").is_some() {
                    return Err("Unsupported export option".into());
                }

                let index = p
                    .get("file")
                    .map(|_| index(p, "file"))
                    .transpose()?
                    .unwrap_or(self.selected_file);
                let file = self.files.get(index).ok_or("Unknown file index")?;
                let document = file
                    .document
                    .as_ref()
                    .ok_or("File has no decoded document")?;
                let format = p["format"]
                    .as_str()
                    .filter(|s| matches!(*s, "csv" | "json"))
                    .ok_or("Format must be csv or json")?;
                let text = if format == "csv" {
                    document.to_csv()
                } else {
                    document.to_json().map_err(|e| e.to_string())?
                };
                Ok(json!({"filename":export_name(&file.name,format),"format":format,"text":text}))
            }
            "preferences" => {
                let encoding = p
                    .get("encoding")
                    .map(|v| match v.as_str() {
                        Some("auto") => Ok(TextEncoding::Auto),
                        Some("utf-8") => Ok(TextEncoding::Utf8),
                        Some("windows-1252") => Ok(TextEncoding::Windows1252),
                        Some("latin1") => Ok(TextEncoding::Latin1),
                        _ => Err("Unknown text encoding"),
                    })
                    .transpose()?;
                let theme = p
                    .get("theme")
                    .map(|v| match v.as_str() {
                        Some("system") => Ok(egui::ThemePreference::System),
                        Some("dark") => Ok(egui::ThemePreference::Dark),
                        Some("light") => Ok(egui::ThemePreference::Light),
                        _ => Err("Unknown theme"),
                    })
                    .transpose()?;
                if encoding.is_some() && self.busy() {
                    return Err("Wait for pending reads before changing encoding".into());
                }
                if let Some(encoding) = encoding {
                    self.encoding = encoding;
                    self.reparse(ctx);
                }
                if let Some(theme) = theme {
                    ctx.set_theme(theme);
                }
                Ok(json!({"updated":true}))
            }
            _ => Err(format!("Unknown command {}", command.method)),
        }
    }
    fn current_file(&self) -> Result<&OpenFile, String> {
        self.files
            .get(self.selected_file)
            .ok_or("No selected file".into())
    }
    fn current_file_mut(&mut self) -> Result<&mut OpenFile, String> {
        self.files
            .get_mut(self.selected_file)
            .ok_or("No selected file".into())
    }
    fn current_plot_mut(&mut self) -> Result<&mut SpectrumPlot, String> {
        if self.overlay {
            if self.overlay_units.is_none() {
                return Err("No overlay spectrum".into());
            }
            Ok(&mut self.overlay_plot)
        } else {
            let file = self.current_file_mut()?;
            if file.document.as_ref().is_none_or(|d| d.series.is_empty()) {
                return Err("No selected series".into());
            }
            Ok(&mut file.plot)
        }
    }
    fn control_state(&self, ctx: &egui::Context) -> Value {
        let plot = if self.overlay {
            Some(self.overlay_plot.snapshot())
        } else {
            self.files
                .get(self.selected_file)
                .filter(|f| f.document.as_ref().is_some_and(|d| !d.series.is_empty()))
                .map(|f| f.plot.snapshot())
        };
        json!({"frame":ctx.cumulative_frame_nr(),"busy":self.busy(),"status":self.status,"view":if self.overlay{"overlay"}else{"individual"},"selectedFile":self.selected_file,"overlayUnits":self.overlay_units,"plot":plot,"encoding":encoding_name(self.encoding),"theme":match ctx.options(|o|o.theme_preference){egui::ThemePreference::System=>"system",egui::ThemePreference::Light=>"light",egui::ThemePreference::Dark=>"dark"},"effectiveTheme":if ctx.theme()==egui::Theme::Dark{"dark"}else{"light"},"files":self.files.iter().enumerate().map(|(index,f)|json!({"index":index,"name":f.name,"error":f.error,"bytes":f.bytes.as_ref().map(|b|b.len()),"included":f.overlay_enabled,"selectedSeries":f.selected_series,"reverseX":f.reverse_x,"series":f.document.as_ref().map(|d|d.series.iter().enumerate().map(|(index,s)|json!({"index":index,"name":s.name,"kind":s.kind,"points":s.y.len(),"xUnitCode":s.metadata.x_unit_code,"yUnitCode":s.metadata.y_unit_code})).collect::<Vec<_>>())})).collect::<Vec<_>>()})
    }
    fn inspect_command(&self, p: &Value) -> Reply {
        let file = self
            .files
            .get(
                p.get("file")
                    .map(|_| index(p, "file"))
                    .transpose()?
                    .unwrap_or(self.selected_file),
            )
            .ok_or("Unknown file index")?;
        let document = file
            .document
            .as_ref()
            .ok_or("File has no decoded document")?;
        let scope = p["scope"].as_str().ok_or("Missing inspection scope")?;
        let value = {
            let value: Value =
                serde_json::from_str(&document.to_json().map_err(|e| e.to_string())?)
                    .map_err(|e| e.to_string())?;
            match scope {
                "document" => value,
                "series" => value["series"]
                    .get(
                        p.get("index")
                            .map(|_| index(p, "index"))
                            .transpose()?
                            .unwrap_or(file.selected_series),
                    )
                    .cloned()
                    .ok_or("Unknown series index")?,
                "section" => value["sections"]
                    .get(index(p, "index")?)
                    .cloned()
                    .ok_or("Unknown section index")?,
                "object" => value["embeddedObjects"]
                    .get(index(p, "index")?)
                    .cloned()
                    .ok_or("Unknown object index")?,
                _ => return Err("Unknown inspection scope".into()),
            }
        };
        let mut value = value;
        trim_data(
            &mut value,
            p["includeData"] == true,
            p["includePayload"] == true,
        );
        Ok(json!({"scope":scope,"data":value}))
    }
    fn ui_command(&mut self, p: &Value, ctx: &egui::Context) -> Reply {
        let action = p["action"].as_str().ok_or("Missing UI action")?;
        if !self.control.deferred_input.is_empty() {
            return Err("Wait for the previous UI input action".into());
        }
        let node = p
            .get("id")
            .map(|id| {
                id.as_str()
                    .and_then(|s| s.parse::<u64>().ok())
                    .and_then(|id| self.control.nodes.get(&id).map(|n| (id, n.clone())))
                    .ok_or("Unknown UI node ID; inspect ui.elements again")
            })
            .transpose()?;
        if node
            .as_ref()
            .is_some_and(|(_, n)| n.is_disabled() || n.is_hidden())
        {
            return Err("UI node is disabled or hidden".into());
        }
        let modifiers = egui::Modifiers {
            ctrl: p["ctrl"] == true && !cfg!(target_os = "macos"),
            mac_cmd: p["ctrl"] == true && cfg!(target_os = "macos"),
            command: p["ctrl"] == true,
            shift: p["shift"] == true,
            ..Default::default()
        };
        let point = || -> Result<egui::Pos2, String> {
            if p.get("x").is_some() {
                Ok(egui::pos2(point_number(p, "x")?, point_number(p, "y")?))
            } else {
                let bounds = node
                    .as_ref()
                    .and_then(|(_, n)| n.bounds())
                    .ok_or("Node has no bounds; specify x and y")?;
                Ok(egui::pos2(
                    ((bounds.x0 + bounds.x1) / 2.0) as f32,
                    ((bounds.y0 + bounds.y1) / 2.0) as f32,
                ))
            }
        };
        let event = match action {
            "hover" | "pointerMove" => egui::Event::PointerMoved(point()?),
            "pointerDown" | "pointerUp" => egui::Event::PointerButton {
                pos: point()?,
                button: egui::PointerButton::Primary,
                pressed: action == "pointerDown",
                modifiers,
            },
            "wheel" => {
                self.control.input.push(egui::Event::PointerMoved(point()?));
                egui::Event::MouseWheel {
                    unit: egui::MouseWheelUnit::Point,
                    phase: egui::TouchPhase::Move,
                    delta: egui::vec2(0.0, point_number(p, "deltaY")?),
                    modifiers,
                }
            }
            "key" => {
                let key = match p["key"].as_str() {
                    Some("ArrowLeft") => egui::Key::ArrowLeft,
                    Some("ArrowRight") => egui::Key::ArrowRight,
                    Some("ArrowUp") => egui::Key::ArrowUp,
                    Some("ArrowDown") => egui::Key::ArrowDown,
                    Some("Home") => egui::Key::Home,
                    Some("End") => egui::Key::End,
                    Some("Enter") => egui::Key::Enter,
                    Some("Escape") => egui::Key::Escape,
                    Some("Tab") => egui::Key::Tab,
                    Some("Backspace") => egui::Key::Backspace,
                    Some("Delete") => egui::Key::Delete,
                    Some("A") => egui::Key::A,
                    _ => return Err("Unsupported key".into()),
                };
                self.control.input.push(egui::Event::Key {
                    key,
                    physical_key: None,
                    pressed: true,
                    repeat: false,
                    modifiers,
                });
                egui::Event::Key {
                    key,
                    physical_key: None,
                    pressed: false,
                    repeat: false,
                    modifiers,
                }
            }
            _ => {
                let (id, node) = node.ok_or("This action requires a node ID")?;
                let action = match action {
                    "click" => Action::Click,
                    "focus" => Action::Focus,
                    "setValue" => Action::SetValue,
                    "increment" => Action::Increment,
                    "decrement" => Action::Decrement,
                    "scrollIntoView" => Action::ScrollIntoView,
                    _ => return Err("Unknown UI action".into()),
                };
                if action == Action::SetValue
                    && !node.supports_action(action)
                    && can_set_text(&node)
                {
                    let value = p["value"]
                        .as_str()
                        .ok_or("Text fields require a string value")?;
                    self.control
                        .input
                        .push(egui::Event::AccessKitActionRequest(ActionRequest {
                            action: Action::Focus,
                            target_tree: TreeId::ROOT,
                            target_node: NodeId(id),
                            data: None,
                        }));
                    let command = egui::Modifiers {
                        command: true,
                        ctrl: !cfg!(target_os = "macos"),
                        mac_cmd: cfg!(target_os = "macos"),
                        ..Default::default()
                    };
                    self.control.deferred_input.push_back(vec![
                        egui::Event::Key {
                            key: egui::Key::A,
                            physical_key: None,
                            pressed: true,
                            repeat: false,
                            modifiers: command,
                        },
                        egui::Event::Key {
                            key: egui::Key::A,
                            physical_key: None,
                            pressed: false,
                            repeat: false,
                            modifiers: command,
                        },
                        egui::Event::Text(value.into()),
                    ]);
                    ctx.request_repaint();
                    return Ok(
                        json!({"accepted":true,"queuedForFrame":ctx.cumulative_frame_nr()+2}),
                    );
                }
                if !node.supports_action(action) {
                    return Err("Node does not support this action".into());
                }
                let data = if action == Action::SetValue {
                    Some(if let Some(value) = p["value"].as_f64() {
                        if !value.is_finite() {
                            return Err("Value must be finite".into());
                        }
                        ActionData::NumericValue(value)
                    } else {
                        ActionData::Value(
                            p["value"]
                                .as_str()
                                .ok_or("Value must be text or a number")?
                                .into(),
                        )
                    })
                } else {
                    None
                };
                egui::Event::AccessKitActionRequest(ActionRequest {
                    action,
                    target_tree: TreeId::ROOT,
                    target_node: NodeId(id),
                    data,
                })
            }
        };
        self.control.input.push(event);
        ctx.request_repaint();
        Ok(json!({"accepted":true,"queuedForFrame":ctx.cumulative_frame_nr()+1}))
    }
}
fn can_set_text(node: &Node) -> bool {
    matches!(node.role(), Role::TextInput | Role::MultilineTextInput)
        && node.supports_action(Action::Focus)
        && node.value().is_some()
}
fn number(p: &Value, key: &str) -> Result<f64, String> {
    p[key]
        .as_f64()
        .filter(|v| v.is_finite())
        .ok_or_else(|| format!("{key} must be a finite number"))
}
fn point_number(p: &Value, key: &str) -> Result<f32, String> {
    let value = number(p, key)? as f32;
    if !value.is_finite() {
        return Err(format!("{key} exceeds the coordinate range"));
    }
    Ok(value)
}
fn index(p: &Value, key: &str) -> Result<usize, String> {
    p[key]
        .as_u64()
        .and_then(|i| usize::try_from(i).ok())
        .ok_or_else(|| format!("{key} must be a nonnegative index"))
}
fn u32_number(p: &Value, key: &str) -> Result<u32, String> {
    p[key]
        .as_u64()
        .and_then(|i| u32::try_from(i).ok())
        .ok_or_else(|| format!("{key} must be a uint32 code"))
}

fn trim_data(value: &mut Value, data: bool, payload: bool) {
    match value {
        Value::Object(object) => {
            if !data {
                for key in ["x", "y"] {
                    object.remove(key);
                }
            }
            if !payload {
                for key in [
                    "sourceBytes",
                    "payload",
                    "rawHeader",
                    "rawSettings",
                    "body",
                    "trailingBytes",
                ] {
                    object.remove(key);
                }
            }
            for value in object.values_mut() {
                trim_data(value, data, payload);
            }
        }
        Value::Array(array) => {
            for value in array {
                trim_data(value, data, payload);
            }
        }
        _ => {}
    }
}
